import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test.beforeEach(async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-11T00:00:00Z') })
  await page.clock.pauseAt(new Date('2026-10-11T00:00:00Z'))
  await page.goto('/')
  await expect(page.getByRole('button', { name: '集中をはじめる' })).toBeEnabled()
})

test('20分・25分の境界、超過継続、手動終了、修正保存', async ({ page }) => {
  await page.getByRole('button', { name: '学習項目管理', exact: true }).click()
  await page.getByLabel('数学 · 高校基礎', { exact: false }).check()
  await page.getByRole('button', { name: '選択したテンプレートを追加' }).click()
  await page.getByRole('button', { name: '集中タイマー', exact: true }).click()
  await page.getByLabel('中項目', { exact: true }).selectOption({ label: '数学Ⅰ' })
  await page.getByLabel('小項目', { exact: true }).selectOption({ label: '二次関数' })
  await page.getByRole('button', { name: '集中をはじめる' }).click()
  await page.getByRole('button', { name: /^正解/ }).click()
  await page.getByRole('button', { name: '不正解', exact: false }).click()
  await page.getByLabel('学習メモ').fill('平方完成を復習')
  await page.getByRole('button', { name: '取り消す' }).click()
  await page.clock.fastForward(20 * 60_000 - 1000)
  await expect(page.getByTestId('elapsed')).toHaveText('19:59')
  await expect(page.getByText('20分達成 ·', { exact: false })).toHaveCount(0)
  await page.clock.fastForward(1000)
  await expect(page.getByText('20分達成 ·', { exact: false })).toBeVisible()
  await expect(page.getByRole('status')).toHaveCount(0)
  await page.clock.fastForward(5 * 60_000 - 1000)
  await expect(page.getByRole('status')).toHaveCount(0)
  await page.clock.fastForward(1000)
  await expect(page.getByRole('status')).toContainText('25分に到達')
  await page.getByRole('button', { name: '通知を閉じる' }).click()
  await page.clock.fastForward(2 * 60_000)
  await expect(page.getByTestId('elapsed')).toHaveText('27:00')
  await expect(page.getByText('+02:00 延長中')).toBeVisible()
  await expect(page.getByRole('button', { name: '一時停止' })).toBeVisible()
  await page.getByRole('button', { name: 'このセットを終了' }).click()
  await expect(page.getByRole('heading', { name: 'おつかれさまでした。' })).toBeVisible()
  await page.getByLabel('正解数', { exact: true }).fill('3')
  await page.getByRole('button', { name: 'この内容で保存する' }).click()
  await expect(page.getByRole('button', { name: '集中をはじめる' })).toBeEnabled()
  await expect(page.locator('.session-row')).toContainText('数学 / 数学Ⅰ / 二次関数')
  await expect(page.locator('.session-row')).toContainText('27:00')
  await expect(page.locator('.session-row')).toContainText('3問 / 正答率100%')
  await expect(page.locator('.session-row')).toContainText('平方完成を復習')
  await expect(page.locator('.stat-card').nth(1)).toContainText('1セット')
})

test('一時停止・休憩・集中・確認中をリロード復元する', async ({ page }) => {
  await page.getByRole('button', { name: '集中をはじめる' }).click()
  await page.clock.fastForward(60_000)
  await page.getByRole('button', { name: '一時停止' }).click()
  await page.clock.fastForward(10 * 60_000)
  await page.reload()
  await expect(page.getByText('一時停止中', { exact: true })).toBeVisible()
  await expect(page.getByTestId('elapsed')).toHaveText('01:00')
  await page.getByRole('button', { name: '集中を再開する' }).click()
  await page.clock.fastForward(60_000)
  await page.getByRole('button', { name: '休憩する' }).click()
  await page.clock.fastForward(10 * 60_000)
  await page.reload()
  await expect(page.getByText('休憩中', { exact: true })).toBeVisible()
  await expect(page.getByTestId('elapsed')).toHaveText('02:00')
  await page.getByRole('button', { name: '集中を再開する' }).click()
  await page.clock.fastForward(60_000)
  await page.reload()
  await expect(page.getByTestId('elapsed')).toHaveText('03:00')
  await page.getByRole('button', { name: 'このセットを終了' }).click()
  await page.clock.fastForward(60_000)
  await page.reload()
  await expect(page.getByLabel('集中時間（分）')).toHaveValue('3')
  await page.getByRole('button', { name: 'この内容で保存する' }).click()
  await expect(page.locator('.session-row')).toContainText('03:00')
  await expect(page.locator('.stat-card').nth(1)).toContainText('0セット')
})

test('通知はリロード後に繰り返さず、状態はオフラインで復元できる', async ({ page, context }) => {
  await page.getByRole('button', { name: '集中をはじめる' }).click()
  await page.clock.fastForward(25 * 60_000)
  await expect(page.getByRole('status')).toContainText('25分に到達')
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready
  })
  await page.reload()
  await expect(page.getByRole('status')).toHaveCount(0)
  await expect(page.getByTestId('elapsed')).toHaveText('25:00')
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByTestId('elapsed')).toHaveText('25:00')
  await page.getByRole('button', { name: '一時停止' }).click()
  await expect(page.getByText('一時停止中', { exact: true })).toBeVisible()
})

